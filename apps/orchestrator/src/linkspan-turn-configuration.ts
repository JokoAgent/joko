import { randomUUID } from "node:crypto";
import { create } from "@bufbuild/protobuf";
import { RemoteDesktopIceServerSchema, type RemoteDesktopIceServer } from "@joko/contracts";
import { parseRemoteDesktopIceConfig } from "@joko/device-peer";
import { operationBodyHash, type OperationalStore } from "@joko/store";
import { LinkspanError } from "@jokoagent/linkspan-core";
import { issueCloudflareTurnCredentials, revokeCloudflareTurnCredentials,
  type CloudflareTurnCredentials, type CloudflareTurnResource } from "@jokoagent/linkspan-cloudflare/turn";
import { retireExpiringTurnResource, type TurnCredentials, type ExpiringTurnResource } from "@jokoagent/linkspan-turn";
import type { CredentialManager } from "./credential-manager.js";
import type { OrchestratorConfig } from "./config.js";
import type { RemoteDesktopIceConfigurationProvider } from "./remote-desktop-coordinator.js";
import { publicRemoteDesktopIceConfiguration, readIceToken } from "./remote-desktop-ice-configuration.js";
import { toProtoTimestamp } from "./proto-mapper.js";

const PREFIX = "runtime.linkspan.turn.";
type TurnMaterial = CloudflareTurnCredentials | TurnCredentials;
type TurnResource = CloudflareTurnResource | ExpiringTurnResource;
interface TurnRecord {
  readonly requestId: string;
  readonly leaseId: string;
  readonly keyId: string;
  readonly provider?: "cloudflare" | "twilio" | "coturn";
  readonly reference: string;
  readonly state: "issuing" | "active" | "outcome_unknown" | "retiring" | "closed";
}
type IceInput = Parameters<RemoteDesktopIceConfigurationProvider["getConfiguration"]>[0];

/** Host authorization and receipts stay here; Linkspan only handles provider material. */
export class LinkspanRemoteDesktopTurnConfiguration implements RemoteDesktopIceConfigurationProvider {
  readonly #leases = new Map<string, { readonly promise: Promise<TurnMaterial>; retired: boolean }>();
  readonly #cleanup = new Map<string, Promise<void>>();
  #closed = false;

  constructor(private readonly options: {
    readonly configuration: NonNullable<OrchestratorConfig["remoteDesktopTurn"]>;
    readonly store: OperationalStore;
    readonly credentials: CredentialManager;
    readonly fetch: typeof fetch;
    readonly readToken?: (path: string, signal: AbortSignal) => Promise<string>;
  }) {}

  /** Old media leases do not survive a service restart; retire only our exact handles. */
  async initialize(): Promise<void> {
    for (const { value } of this.options.store.listSettingsByKeyPrefix("service", "orchestrator", PREFIX)) {
      const record = value as TurnRecord;
      this.#reserve(record.reference, record.provider ?? "cloudflare");
      if (record.state === "closed") {
        this.#settleRetiredIssue(record);
        // A completed provider receipt does not prove local secret deletion.
        await this.options.credentials.deleteManagedSecret(record.reference);
        continue;
      }
      if (this.options.credentials.find(record.reference) !== undefined) await this.#retire(record);
      else this.#record({ ...record, state: "outcome_unknown" });
    }
  }

  async getConfiguration(input: IceInput): Promise<readonly RemoteDesktopIceServer[]> {
    input.signal.throwIfAborted(); input.assertCurrent?.();
    if (this.#closed) throw new Error("Hosted TURN is closed.");
    let lease = this.#leases.get(input.leaseId);
    if (lease?.retired) throw new Error("The media lease was retired.");
    // Repeated host/viewer requests for one authorized media lease share the
    // same issuance. A lost issuance is never retried by reconnecting a view.
    if (lease === undefined) {
      lease = { promise: this.#issue(input), retired: false };
      this.#leases.set(input.leaseId, lease);
    }
    try {
      let material = await lease.promise;
      input.signal.throwIfAborted(); input.assertCurrent?.();
      if (lease.retired || this.#closed) throw new Error("The media lease was retired.");
      if (material.expiresAt <= Date.now() + 120_000) {
        // Refresh only a confirmed successful issuance. Rejected/unknown
        // promises never reach here and are not regenerated by reconnecting.
        const current = this.#leases.get(input.leaseId);
        if (current === lease) {
          lease = { promise: this.#issue(input), retired: false };
          this.#leases.set(input.leaseId, lease);
        } else if (current !== undefined) lease = current;
        material = await lease.promise;
        input.signal.throwIfAborted(); input.assertCurrent?.();
        if (lease.retired || this.#closed) throw new Error("The media lease was retired.");
      }
      const now = Date.now();
      const iceServers = material.iceServers.flatMap(server => {
        // The current Joko v1 contract permits four URLs per entry. Keep UDP,
        // TCP and TLS/443 from the real response without weakening its parser.
        const preferred = [...server.urls].sort((a, b) => Number(b.startsWith("turns:") && b.includes(":443?")) - Number(a.startsWith("turns:") && a.includes(":443?")));
        const groups = [];
        for (let offset = 0; offset < preferred.length; offset += 4) groups.push({
          urls: preferred.slice(offset, offset + 4), username: server.username, credential: server.credential
        });
        return groups;
      });
      const servers = parseRemoteDesktopIceConfig({ iceServers, expiresAt: new Date(material.expiresAt).toISOString() }, now);
      return Object.freeze(servers.map(server => create(RemoteDesktopIceServerSchema, {
        urls: [...server.urls], username: server.username, credential: server.credential,
        expiresAt: toProtoTimestamp(material.expiresAt)
      })));
    } catch {
      input.signal.throwIfAborted(); input.assertCurrent?.();
      if (lease.retired || this.#closed) throw new Error("The media lease was retired.");
      // Preserve the existing STUN/JPEG behavior, without retrying the mutation
      // or silently switching to a second TURN provider.
      return publicRemoteDesktopIceConfiguration(Date.now());
    }
  }

  async releaseConfiguration(leaseId: string): Promise<void> {
    const lease = this.#leases.get(leaseId);
    if (lease !== undefined) lease.retired = true;
    try { await lease?.promise; } catch { /* Unknown issuance remains in its original Operation. */ }
    const records = this.options.store.listSettingsByKeyPrefix("service", "orchestrator", PREFIX);
    await Promise.all(records.map(({ value }) => value as TurnRecord)
      .filter(record => record.leaseId === leaseId && record.state !== "closed")
      .map(record => this.#retire(record)));
    this.#leases.delete(leaseId);
  }

  async close(): Promise<void> {
    this.#closed = true;
    await Promise.all([...this.#leases.keys()].map(leaseId => this.releaseConfiguration(leaseId)));
    await Promise.all(this.#cleanup.values());
  }

  #record(record: TurnRecord): void { this.options.store.setSetting("service", "orchestrator", PREFIX + record.requestId, record); }
  #provider(): "cloudflare" | "twilio" | "coturn" { return this.options.configuration.provider ?? "cloudflare"; }
  #reserve(reference: string, provider: "cloudflare" | "twilio" | "coturn" = this.#provider()): void {
    this.options.credentials.reserveManagedSecret({ credentialReferenceId: reference, kind: "header_secret", providerId: `${provider}.turn` });
  }
  #access(assertCurrent?: () => void) {
    return { keyId: this.options.configuration.keyId, fetch: this.options.fetch,
      readApiToken: async (signal: AbortSignal) => {
        signal.throwIfAborted(); assertCurrent?.();
        const token = await (this.options.readToken ?? readIceToken)(this.options.configuration.tokenPath, signal);
        signal.throwIfAborted(); assertCurrent?.();
        return token;
      } };
  }

  async #issue(input: IceInput): Promise<TurnMaterial> {
    const requestId = `turn:${randomUUID()}`;
    const record: TurnRecord = { requestId, leaseId: input.leaseId, keyId: this.options.configuration.keyId,
      ...(this.#provider() === "cloudflare" ? {} : { provider: this.#provider() }),
      reference: `linkspan.turn:${requestId}`, state: "issuing" };
    const claim = this.options.store.claimDeferredEffectOperation({ id: requestId, kind: "connection.turn.issue",
      body: { provider: this.#provider(), keyId: record.keyId, leaseId: record.leaseId, ttlSeconds: this.options.configuration.ttlSeconds } }, () => {
        input.signal.throwIfAborted(); input.assertCurrent?.(); this.#record(record);
      });
    this.#reserve(record.reference);
    let material: TurnMaterial | undefined;
    try {
      const options = { requestId, ttlSeconds: this.options.configuration.ttlSeconds, signal: input.signal };
      const access = this.#access(input.assertCurrent);
      if (this.#provider() === "twilio") {
        const { issueTwilioTurnCredentials } = await import("@jokoagent/linkspan-turn/twilio");
        material = await issueTwilioTurnCredentials({ accountSid: access.keyId, enabled: true, fetch: this.options.fetch,
          readCredentials: async signal => ({ username: access.keyId, secret: await access.readApiToken(signal) }) }, options);
      } else if (this.#provider() === "coturn") {
        const { issueCoturnRestCredentials } = await import("@jokoagent/linkspan-turn/coturn");
        material = await issueCoturnRestCredentials({ keyId: access.keyId, urls: this.options.configuration.urls ?? [], readSharedSecret: access.readApiToken }, options);
      } else material = await issueCloudflareTurnCredentials(access, options);
      const saved = await this.options.credentials.compareAndSetManagedSecret({ credentialReferenceId: record.reference,
        expectedSecret: undefined, secret: JSON.stringify(material.resource), displayName: "Hosted TURN cleanup handle",
        kind: "header_secret", providerId: `${this.#provider()}.turn` });
      if (!saved) throw new Error("The TURN cleanup handle could not be saved.");
      this.options.store.completeDeferredEffectOperation(requestId, claim.operation.bodyHash, () => {
        this.#record({ ...record, state: "active" }); return { state: "active", reference: record.reference };
      });
      input.signal.throwIfAborted(); input.assertCurrent?.();
      return material;
    } catch (error) {
      if (material === undefined && error instanceof LinkspanError && error.outcome === "not_sent") {
        this.options.store.completeDeferredEffectOperation(requestId, claim.operation.bodyHash, () => {
          this.#record({ ...record, state: "closed" }); return { state: "rejected", code: error.code };
        });
        throw error;
      }
      // A failed receipt must not skip cleanup of a resource already known in
      // memory. If durable storage remains unavailable, retain the original
      // operation and protected handle for startup reconciliation.
      try { this.#record({ ...record, state: "outcome_unknown" }); }
      finally { if (material !== undefined) await this.#retire(record, material.resource); }
      throw error;
    }
  }

  #retire(record: TurnRecord, known?: TurnResource): Promise<void> {
    const existing = this.#cleanup.get(record.requestId);
    if (existing !== undefined) return existing;
    const pending = this.#retireOwned(record, known).finally(() => this.#cleanup.delete(record.requestId));
    this.#cleanup.set(record.requestId, pending);
    return pending;
  }

  async #retireOwned(record: TurnRecord, known?: TurnResource): Promise<void> {
    if (record.keyId !== this.options.configuration.keyId || (record.provider ?? "cloudflare") !== this.#provider()) return this.#diagnose(record);
    let resource = known;
    if (resource === undefined) {
      if (this.options.credentials.find(record.reference) === undefined) return this.#diagnose(record);
      try { resource = JSON.parse(this.options.credentials.resolve(record.reference)) as TurnResource; }
      catch { return this.#diagnose(record); }
    }
    if (resource.requestId !== record.requestId || resource.keyId !== record.keyId || resource.kind !== `${this.#provider()}.turn`) return this.#diagnose(record);
    const cleanupId = `${record.requestId}:revoke`;
    let operation = this.options.store.findOperation(cleanupId);
    if (operation === undefined) operation = this.options.store.claimDeferredEffectOperation({ id: cleanupId,
      kind: "connection.turn.revoke", body: { reference: record.reference, issueRequestId: record.requestId } }).operation;
    if (operation.kind !== "connection.turn.revoke" || operation.connectionId !== undefined || operation.completionMode !== "external_effect"
      || operation.bodyHash !== operationBodyHash({ reference: record.reference, issueRequestId: record.requestId })) return this.#diagnose(record);
    if (operation.status !== "completed") {
      this.#record({ ...record, state: "retiring" });
      try {
        let retirement: unknown;
        if (resource.kind === "cloudflare.turn") await revokeCloudflareTurnCredentials(this.#access(), resource, { requestId: cleanupId, deadline: Date.now() + 3_000 });
        else retirement = retireExpiringTurnResource(resource, { kind: resource.kind, keyId: record.keyId, issueRequestId: record.requestId });
        this.options.store.completeDeferredEffectOperation(cleanupId, operation.bodyHash, () => {
          this.#record({ ...record, state: "closed" }); return { state: "closed", ...(retirement === undefined ? {} : { providerRetirement: retirement }) };
        });
      } catch { this.#diagnose(record); return; }
    }
    this.#record({ ...record, state: "closed" });
    this.#settleRetiredIssue(record);
    await this.options.credentials.deleteManagedSecret(record.reference);
  }

  #settleRetiredIssue(record: TurnRecord): void {
    const cleanup = this.options.store.findOperation(`${record.requestId}:revoke`);
    const issue = this.options.store.findOperation(record.requestId);
    if (cleanup?.status !== "completed" || cleanup.kind !== "connection.turn.revoke" || cleanup.connectionId !== undefined
      || cleanup.completionMode !== "external_effect" || cleanup.bodyHash !== operationBodyHash({ reference: record.reference, issueRequestId: record.requestId })
      || issue?.status !== "started" || issue.kind !== "connection.turn.issue" || issue.connectionId !== undefined || issue.completionMode !== "external_effect") return;
    this.options.store.completeDeferredEffectOperation(record.requestId, issue.bodyHash, () => ({ state: "closed",
      reason: "issued_then_retired_after_receipt_failure", cleanupOperationId: cleanup.id }));
  }

  #diagnose(record: TurnRecord): void {
    this.options.store.appendDiagnostic({ severity: "warning", component: "linkspan.turn", code: "TURN_CLEANUP_UNCONFIRMED",
      message: "A hosted TURN resource remains unconfirmed. Restore its original provider access and reconcile the saved operation.",
      details: { requestId: record.requestId } });
  }
}
