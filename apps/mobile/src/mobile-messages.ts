const catalogs: Readonly<Record<MobileSupportedLocale, MobileMessageCatalog>> = {
  en,
  "zh-CN": zhCN,
  "zh-TW": zhTW,
  ja,
  ko
};

export function mobileMessage(
  locale: MobileSupportedLocale,
  key: MobileMessageKey,
  variables: Readonly<Record<string, string | number>> = {}
): string {
  const template = catalogs[locale]?.[key];
  if (typeof template !== "string") throw new Error(`Missing mobile message: ${locale}/${key}`);
  const expected = placeholders(template);
  const actual = Object.keys(variables).sort();
  if (expected.length !== actual.length || expected.some((name, index) => name !== actual[index])) {
    throw new Error(`Invalid variables for mobile message: ${key}`);
  }
  return template.replace(/\{([a-z][A-Za-z0-9]*)\}/gu, (_match, name: string) => String(variables[name]!));
}

function placeholders(value: string): string[] {
  return [...value.matchAll(/\{([a-z][A-Za-z0-9]*)\}/gu)].map((match) => match[1]!).sort();
}

export const mobileMessagesTesting = { catalogs, placeholders };
